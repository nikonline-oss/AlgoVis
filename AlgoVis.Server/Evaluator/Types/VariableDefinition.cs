using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace AlgoVis.Evaluator.Evaluator.Types
{
    /// <summary>
    /// Определение переменной для системы визуализации алгоритмов.
    /// 
    /// Содержит метаданные, необходимые для создания и инициализации переменной
    /// в контексте выполнения алгоритма.
    /// </summary>
    public class VariableDefinition
    {
        /// <summary>
        /// Имя переменной.
        /// 
        /// Должно быть уникальным в пределах текущего контекста выполнения.
        /// Используется для доступа к переменной в алгоритмах.
        /// </summary>
        public string name { get; set; } = string.Empty;

        /// <summary>
        /// Тип переменной.
        /// 
        /// Строковое представление типа. По умолчанию "int".
        /// Может принимать значения: "int", "double", "bool", "string" и другие.
        /// </summary>
        public string type { get; set; } = "int";

        /// <summary>
        /// Начальное значение переменной.
        /// 
        /// Объект, содержащий значение инициализации переменной.
        /// Может быть любого типа, соответствующего указанному типу переменной.
        /// </summary>
        public object initialValue { get; set; } = "0";

        /// <summary>
        /// Описание переменной.
        /// 
        /// Содержит пояснительную информацию о назначении переменной
        /// в контексте алгоритма. Может использоваться для документации
        /// и подсказок в интерфейсе визуализатора.
        /// </summary>
        /// <remarks>
        /// Это поле часто используется для предоставления контекстной
        /// информации пользователю о том, какую роль играет переменная
        /// в алгоритме.
        /// </remarks>
        public string description { get; set; } = string.Empty;
    }
}